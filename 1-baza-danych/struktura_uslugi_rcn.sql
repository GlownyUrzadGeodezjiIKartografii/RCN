--
-- Name: mv_powiaty; Type: MATERIALIZED VIEW; Schema: uslugi_rcn; Owner: -
--

CREATE MATERIALIZED VIEW uslugi_rcn.mv_powiaty AS
 SELECT p.id,
    p.teryt,
    p.serwis_rcn,
    p.start_obiekt,
    p.geometria,
    odi.id AS otwarte_dane_instytucja_id,
    odi.url_rcn,
    odi.api_url_rcn,
    (p.data_aktualizacji_danych)::date AS data_aktualizacji_danych,
    (p.data_aktualizacji_geometrii)::date AS data_aktualizacji_geometrii,
    p.status,
    (EXISTS ( SELECT 1
           FROM ((uslugi_rcn.dzialka d
             JOIN uslugi_rcn.nieruchomosc n ON ((n.id = d.id_nieruchomosci)))
             JOIN uslugi_rcn.transakcja t ON ((t.id = n.id_transakcji)))
          WHERE (((t.teryt_powiatu)::text = (p.teryt)::text) AND (d.geometria IS NOT NULL))
        UNION ALL
         SELECT 1
           FROM ((uslugi_rcn.budynek b
             JOIN uslugi_rcn.nieruchomosc n ON ((n.id = b.id_nieruchomosci)))
             JOIN uslugi_rcn.transakcja t ON ((t.id = n.id_transakcji)))
          WHERE (((t.teryt_powiatu)::text = (p.teryt)::text) AND (b.geometria IS NOT NULL))
        UNION ALL
         SELECT 1
           FROM ((uslugi_rcn.lokal l
             JOIN uslugi_rcn.nieruchomosc n ON ((n.id = l.id_nieruchomosci)))
             JOIN uslugi_rcn.transakcja t ON ((t.id = n.id_transakcji)))
          WHERE (((t.teryt_powiatu)::text = (p.teryt)::text) AND (l.georeferencja IS NOT NULL))
 LIMIT 1)) AS czy_dane_maja_geometrie
   FROM (uslugi_rcn.powiat p
     LEFT JOIN uslugi_rcn.otwarte_dane_instytucja odi ON ((odi.teryt = (p.teryt)::text)))
  WITH NO DATA;


