CREATE MATERIALIZED VIEW uslugi_rcn.mv_budynki AS
 SELECT b.id AS gid,
    COALESCE(b.geometria, public.st_geomfromtext('POLYGON EMPTY'::text, 2180)) AS geom,
    p.serwis_rcn,
    t.teryt_powiatu AS teryt,
    t.iip_przestrzen_nazw AS tran_przestrzen_nazw,
    t.iip_lokalny_id AS tran_lokalny_id_iip,
    t.iip_wersja_id AS tran_wersja_id,
    t.oznaczenie_transakcji AS tran_oznaczenie_trans,
    COALESCE(s_rt.nazwa, (t.rodzaj_transakcji)::text) AS tran_rodzaj_trans,
    COALESCE(s_rr.nazwa, (t.rodzaj_rynku)::text) AS tran_rodzaj_rynku,
    COALESCE(s_ss.nazwa, (t.strona_sprzedajaca)::text) AS tran_sprzedajacy,
    COALESCE(s_sk.nazwa, (t.strona_kupujaca)::text) AS tran_kupujacy,
    t.cena_brutto AS tran_cena_brutto,
    t.kwota_vat AS tran_vat,
    t.dok_oznaczenie,
    t.dok_data_sporz AS dok_data,
    t.dok_tworca,
    COALESCE(s_rn.nazwa, (n.rodzaj_nieruchomosci)::text) AS nier_rodzaj,
    COALESCE(s_rp.nazwa, (n.rodzaj_prawa)::text) AS nier_prawo,
    n.udzial AS nier_udzial,
    n.pole_pow_gruntowej AS nier_pow_gruntu,
    n.opis AS nier_opis,
    n.cena_brutto AS nier_cena_brutto,
    n.kwota_vat AS nier_vat,
    b.id_budynku AS bud_id_budynku,
    b.nr_budynku AS bud_nr_budynku,
    COALESCE(s_rb.nazwa, (b.rodzaj_budynku)::text) AS bud_rodzaj,
    b.powa_uzytkowa AS bud_pow_uzyt,
    b.cena_brutto AS bud_cena_brutto,
    b.kwota_vat AS bud_vat,
    b.dodatkowe_informacje AS bud_info,
    b.adres_serial AS bud_adres,
    b.centroid AS bud_centroid
   FROM ((((((((((uslugi_rcn.budynek b
     LEFT JOIN uslugi_rcn.nieruchomosc n ON ((n.id = b.id_nieruchomosci)))
     LEFT JOIN uslugi_rcn.transakcja t ON ((t.id = n.id_transakcji)))
     LEFT JOIN uslugi_rcn.powiat p ON (((p.teryt)::text = (t.teryt_powiatu)::text)))
     LEFT JOIN uslugi_rcn.rodzaj_transakcji s_rt ON ((s_rt.kod = t.rodzaj_transakcji)))
     LEFT JOIN uslugi_rcn.rodzaj_rynku s_rr ON ((s_rr.kod = t.rodzaj_rynku)))
     LEFT JOIN uslugi_rcn.strona_transakcji s_ss ON ((s_ss.kod = t.strona_sprzedajaca)))
     LEFT JOIN uslugi_rcn.strona_transakcji s_sk ON ((s_sk.kod = t.strona_kupujaca)))
     LEFT JOIN uslugi_rcn.rodzaj_nieruchomosci s_rn ON ((s_rn.kod = n.rodzaj_nieruchomosci)))
     LEFT JOIN uslugi_rcn.rodzaj_prawa s_rp ON ((s_rp.kod = n.rodzaj_prawa)))
     LEFT JOIN uslugi_rcn.rodzaj_budynku s_rb ON ((s_rb.kod = b.rodzaj_budynku)))
  WHERE (t.teryt_powiatu IS NOT NULL)
  WITH NO DATA;


